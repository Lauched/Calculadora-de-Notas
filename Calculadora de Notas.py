while NOTA02 < 0 or NOTA02 > 10:
    print("NOTA INVÁLIDA! A NOTA DEVE ESTAR ENTRE 0 E 10.")
    NOTA02 = float(input("DIGITE A SEGUNDA NOTA NOVAMENTE:\n"))

